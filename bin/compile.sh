#!/bin/bash
# This script compiles the tool in the given folder to WebAssembly. Invoked by compile.py; do not call directly.
. bin/shared.sh
DIR_BIN=$(pwd)/bin

usage="Do not call compile.sh directly; see README"
DIR_TOOL=${1?$usage}
# Exported so a tool's compile.sh can build versions differently
export BRANCH=${2?$usage}
TOOL=$(basename $DIR_TOOL)


# ------------------------------------------------------------------------------
# Setup codebase
# ------------------------------------------------------------------------------

echo "——————————————————————————————————————————————————"
echo "🧬 $TOOL, branch '$BRANCH'"
echo "——————————————————————————————————————————————————"

function log() {
	BLUE="\033[1;34m"
	OFF="\033[0m"
	echo -e "$BLUE> $1$OFF"
}

# Prepare build folder. Empty it first: otherwise a failed build leaves the previous
# version's files behind and they get copied out as if they were freshly built.
cd $DIR_TOOL
mkdir -p build/
rm -f build/*
cd src/

# Apply patches, if any
patch_file=../patches/${BRANCH}.patch
if [[ -f "$patch_file" ]]; then
	log "Applying patch file <$patch_file>..."
	git apply -v $patch_file
else
	log "No patch file found at <$patch_file>"
fi


# ------------------------------------------------------------------------------
# Compile tool
# ------------------------------------------------------------------------------

log "Compiling..."
../compile.sh

# Finalize glue code (there can be more than one program per tool, e.g. coreutils has many utilities)
log "Finalizing glue code..."
for glueCode in $(ls ../build/*.js);
do
	# Prepend info about biowasm
	echo "// Auto-generated by biowasm; see biowasm.com for details." > "${glueCode}.tmp"
	cat "$glueCode" >> "${glueCode}.tmp"
	mv "${glueCode}.tmp" "$glueCode"
done

# A non-SIMD build that includes bin/simd.js loads <program>-simd.wasm with its own glue
# code, which only works if the SIMD build's glue is identical apart from the file names
for glueSIMD in ../build/*-simd.js; do
	glue=${glueSIMD%-simd.js}.js
	program=$(basename ${glue%.js})
	grep -q "ModuleNoSIMD" "$glue" 2>/dev/null || continue
	if ! cmp -s <(sed "s/${program}-simd\./${program}./g" "$glueSIMD") <(head -n -$(wc -l < $DIR_BIN/simd.js) "$glue"); then
		echo "ERROR: $glueSIMD and $glue have different glue code, so $glue can't load the SIMD .wasm" >&2
		exit 1
	fi
done
